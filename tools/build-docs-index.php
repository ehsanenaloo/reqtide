<?php

declare(strict_types=1);

/**
 * Builds docs/search-index.js, the client-side search index of the documentation site.
 *
 *   php tools/build-docs-index.php            write docs/search-index.js
 *   php tools/build-docs-index.php --check    exit 1 when the file is not what the pages produce (no write)
 *
 * It reads docs/index.html and every docs/guides/*.html, in the order of the sidebar of docs/guides/index.html,
 * and records for each page its title (the h1), address, meta description, h2 headings (id and text) and the
 * visible prose text. The output is deterministic: no timestamps, a fixed order and a fixed JSON encoding, so a
 * second run produces the same bytes. docs/app.js loads the file as `window.RT_DOCS`.
 *
 * Exit status: 0 on success or when in sync, 1 when `--check` finds a difference, 2 on a setup error.
 */

$root = dirname(__DIR__);
$docs = $root . '/docs';
$target = $docs . '/search-index.js';

$read = static function (string $path): string {
    $content = file_get_contents($path);
    if ($content === false) {
        fwrite(STDERR, "build-docs-index: cannot read {$path}\n");
        exit(2);
    }

    return str_replace("\r\n", "\n", $content);
};

$decode = static fn(string $text): string => html_entity_decode($text, ENT_QUOTES | ENT_HTML5, 'UTF-8');
$squash = static fn(string $text): string => trim(preg_replace('~\s+~u', ' ', $text) ?? $text);

// Page order: the sidebar of the guide library, then the home page first.
$library = $read($docs . '/guides/index.html');
if (!preg_match('~<nav aria-label="Guides">(.*?)</nav>~s', $library, $nav)) {
    fwrite(STDERR, "build-docs-index: the guide sidebar is missing from docs/guides/index.html\n");
    exit(2);
}
preg_match_all('~<a href="([^"]+\.html)"~', $nav[1], $links);
$paths = ['index.html'];
foreach ($links[1] as $href) {
    $paths[] = 'guides/' . $href;
}
$paths = array_values(array_unique($paths));

$entries = [];
foreach ($paths as $path) {
    $file = $docs . '/' . $path;
    if (!is_file($file)) {
        fwrite(STDERR, "build-docs-index: {$path} is listed in the sidebar but does not exist\n");
        exit(2);
    }
    $html = $read($file);
    if (!preg_match('~<h1[^>]*>(.*?)</h1>~s', $html, $h1)) {
        fwrite(STDERR, "build-docs-index: {$path} has no h1\n");
        exit(2);
    }
    $description = preg_match('~<meta name="description" content="([^"]*)"~', $html, $d) === 1 ? $decode($d[1]) : '';

    // The searchable text is the article (or, on the library and home pages, the main element).
    if (preg_match('~<article class="prose">(.*?)</article>~s', $html, $body) !== 1 && preg_match('~<main id="main">(.*?)</main>~s', $html, $body) !== 1) {
        fwrite(STDERR, "build-docs-index: {$path} has no article or main element\n");
        exit(2);
    }
    $content = $body[1];
    $headings = [];
    if (preg_match_all('~<h2 id="([^"]+)"[^>]*>(.*?)</h2>~s', $content, $hs, PREG_SET_ORDER)) {
        foreach ($hs as $h) {
            $text = $squash($decode(strip_tags(preg_replace('~<a class="anchor".*?</a>~s', '', $h[2]) ?? $h[2])));
            $headings[] = [$h[1], $text];
        }
    }
    $content = preg_replace('~<(script|style)\b.*?</\1>~s', '', $content) ?? $content;
    $content = preg_replace('~<a class="anchor".*?</a>~s', '', $content) ?? $content;
    $content = preg_replace('~<pre\b.*?</pre>~s', ' ', $content) ?? $content; // code is found by its prose, not by token soup
    $text = $squash($decode(strip_tags(str_replace('>', '> ', $content))));

    $title = $squash($decode(strip_tags($h1[1])));
    if ($path === 'index.html') {
        $title = 'Reqtide PHP documentation';
    }
    if ($path === 'index.html' || $path === 'guides/index.html') {
        // These two pages only list the guides. Indexing their text would put them above the guide a reader wants.
        $headings = [];
        $text = '';
    }
    $entries[] = ['t' => $title, 'u' => $path, 'd' => $description, 'h' => $headings, 'x' => $text];
}

$json = json_encode($entries, JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE | JSON_THROW_ON_ERROR);
$output = "/* Generated by tools/build-docs-index.php. Do not edit by hand. */\nwindow.RT_DOCS = " . $json . ";\n";

if (in_array('--check', $argv, true)) {
    if (!is_file($target) || $read($target) !== $output) {
        fwrite(STDERR, "build-docs-index: docs/search-index.js is out of date. Run: php tools/build-docs-index.php\n");
        exit(1);
    }
    echo 'build-docs-index: docs/search-index.js is up to date (' . count($entries) . " pages)\n";
    exit(0);
}

file_put_contents($target, $output);
echo 'build-docs-index: wrote docs/search-index.js (' . count($entries) . ' pages, ' . strlen($output) . " bytes)\n";
